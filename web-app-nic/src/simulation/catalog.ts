const byId = new Map(CATALOG.map((c) => [c.id, c]));

export function getComponent(id: string | null | undefined): SpacecraftComponent | undefined {
  if (!id) return undefined;
  return byId.get(id);
}

export function componentsFor(subsystem: Subsystem): readonly SpacecraftComponent[] {
  return CATALOG.filter((c) => c.subsystem === subsystem);
}
