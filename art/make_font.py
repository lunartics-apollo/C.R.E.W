def main():
    chars = list(G.keys())
    rows = (len(chars) + COLS - 1) // COLS
    atlas = Image.new("RGBA", (COLS * CELL_W, rows * CELL_H), (0, 0, 0, 0))
    widths = []
    for i, ch in enumerate(chars):
        glyph = G[ch].split(" ")
        widths.append(len(glyph[0]))
        ox, oy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        for y, row in enumerate(glyph):
            for x, px in enumerate(row):
                if px == "#":
                    atlas.putpixel((ox + x, oy + y), (255, 255, 255, 255))
    OUT.mkdir(parents=True, exist_ok=True)
    atlas.save(OUT / "font.png")
    meta = {"cell": [CELL_W, CELL_H], "cols": COLS, "ascent": ASCENT, "height": 9,
            "chars": chars, "widths": widths}
    (OUT / "font.json").write_text(json.dumps(meta, ensure_ascii=False), encoding="utf-8")
    print(f"Pixel font: {len(chars)} glyphs")


if __name__ == "__main__":
    main()
